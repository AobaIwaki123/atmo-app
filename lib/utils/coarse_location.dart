/// プライバシーバイデザインに基づく位置情報粗視化 (Coarse Location) ユーティリティ
class CoarseLocation {
  /// 緯度経度を 0.1 度（約 10km 四方の固定メッシュ代表点）にスナップ（四捨五入）します。
  ///
  /// 気圧推移および気象病予測は大気規模の現象（数十km〜数百km）であるため、
  /// ピンポイントな座標（建物・自宅特定レベル）は不要です。
  /// この丸め処理により、開発者やサーバーログに対する高精度位置情報アクセスを構造的に排除します。
  static double snap(double coordinate) {
    return (coordinate * 10).round() / 10;
  }
}
